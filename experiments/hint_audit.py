"""Manual audit of every hint the BROAD leak measure flagged (experiment 2).

The broad measure flags any appearance of the answer's value, so it over-counts.
Each flagged hint was read by hand and labeled below. Re-run to rebuild
experiments/hint_audit.md:  .venv/bin/python experiments/hint_audit.py

Labels:
  leak          the hint/step lets the student read off the final answer
  borderline    shows the answer's x-term but a real step (e.g. 4 - 4) remains
  false alarm   the number appears for another reason (a coefficient, "2x = 0", ...)
  wrong prose   not a leak, but the text says something false (SymPy can't check prose)
Only broad-flagged hints were audited, so "wrong prose" counts are lower bounds.
"""

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
RUNS = {
    "claude-opus-5-5": REPO / "experiments/results/hints-claude-opus-5-5-2026-11-14-rescored.jsonl",
    "claude-haiku-5-5": REPO / "experiments/results/hints-claude-haiku-5-5-2026-11-14-rescored.jsonl",
}
FA = "false alarm"
# (model, condition, row index) -> (label, reason)
LABELS = {
    **{("claude-opus-5-5", c, i): (FA, "number is a coefficient/constant, or '2x = 0' still needs a step")
       for c in ("without_check", "with_check") for i in (39, 68, 90, 91, 92, 93, 98, 102, 103, 114)},
    **{("claude-opus-5-5", c, 69): ("leak", "'0 divided by any nonzero number is 0' tells the student x = 0")
       for c in ("without_check", "with_check")},
    ("claude-haiku-5-5", "without_check", 12): ("borderline", "says -5x + x = -4x; constants 4 - 4 still to combine"),
    ("claude-haiku-5-5", "without_check", 17): ("leak", "next_step is the final answer 2x - 14"),
    **{("claude-haiku-5-5", "without_check", i): ("leak", "next_step is the fully expanded final answer")
       for i in (20, 21, 22, 24, 25, 26, 27, 28, 29)},
    **{("claude-haiku-5-5", "without_check", i): (FA, "number is a coefficient/constant, or '2x = 0' still needs a step")
       for i in (39, 68, 69, 81, 90, 92, 97, 98, 102, 103, 114)},
    ("claude-haiku-5-5", "with_check", 12): ("borderline", "step -4x + 4 - 4; constants still to combine"),
    **{("claude-haiku-5-5", "with_check", i): (FA, "number is a coefficient/constant, or '2x = 0' still needs a step")
       for i in (39, 68, 81, 90, 92, 98, 102, 103, 114)},
    **{("claude-haiku-5-5", c, i): ("wrong prose", "tells the student their correct step 3x = 9 is wrong")
       for c in ("without_check", "with_check") for i in (91, 93)},
}


def main():
    lines = ["# Experiment 2: manual audit of broad-flagged hints", "",
             "Generated by `experiments/hint_audit.py` (labels and reasons are in that file).", ""]
    summary = ["| model | condition | n | broad-flagged | leak | borderline | wrong prose | false alarm |",
               "|---|---|---|---|---|---|---|---|"]
    detail = []
    for model, path in RUNS.items():
        rows = [json.loads(line) for line in path.read_text().splitlines()]
        for cond in ("without_check", "with_check"):
            flagged = [(i, r) for i, r in enumerate(rows) if r[cond].get("leak_broad")]
            counts = {"leak": 0, "borderline": 0, "wrong prose": 0, FA: 0}
            detail += ["", f"## {model} / {cond.replace('_', ' ')}", "",
                       "| # | skill/state | current | answer | hint | next_step | label | reason |",
                       "|---|---|---|---|---|---|---|---|"]
            for i, r in flagged:
                if (model, cond, i) not in LABELS:
                    raise SystemExit(f"unlabeled flagged hint: {model} {cond} #{i}: {r[cond]['hint']}")
                label, reason = LABELS[(model, cond, i)]
                counts[label] += 1
                h = r[cond]
                detail.append(f"| {i} | {r['skill']}/{r['state']} | `{r['current']}` | {r['answer']} | "
                              f"{h['hint'].replace('|', '/')} | `{h['next_step']}` | **{label}** | {reason} |")
            summary.append(f"| {model} | {cond.replace('_', ' ')} | {len(rows)} | {len(flagged)} | "
                           f"{counts['leak']} | {counts['borderline']} | {counts['wrong prose']} | {counts[FA]} |")
    out = REPO / "experiments/hint_audit.md"
    out.write_text("\n".join(lines + summary + detail) + "\n")
    print("\n".join(summary))


if __name__ == "__main__":
    main()
